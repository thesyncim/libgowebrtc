#!/bin/bash
#
# Build libwebrtc from source at a pinned revision and install it into a local
# prefix that libgowebrtc's Bazel build can consume.
#
# Linux builds use use_custom_libcxx=false so the resulting libwebrtc archive
# links cleanly with the shim's libstdc++-based toolchain.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

WEBRTC_GIT_REV="${WEBRTC_GIT_REV:-d2eaa5570fc9959f8dbde32912a16366b8ee75f4}"
WEBRTC_BRANCH_HEAD="${WEBRTC_BRANCH_HEAD:-7390}"
WEBRTC_CACHE_DIR="${WEBRTC_CACHE_DIR:-$HOME/.cache/libgowebrtc/webrtc}"
DEPOT_TOOLS_DIR="${DEPOT_TOOLS_DIR:-$HOME/.cache/libgowebrtc/depot_tools}"
TARGET_PLATFORM="${TARGET_PLATFORM:-}"
INSTALL_DIR="${INSTALL_DIR:-$HOME/libwebrtc}"
WEBRTC_INSTALL_BUILD_DEPS="${WEBRTC_INSTALL_BUILD_DEPS:-0}"
WEBRTC_GCLIENT_JOBS="${WEBRTC_GCLIENT_JOBS:-2}"

log_info()    { echo -e "\033[0;34m[INFO]\033[0m $1"; }
log_success() { echo -e "\033[0;32m[SUCCESS]\033[0m $1"; }
log_error()   { echo -e "\033[0;31m[ERROR]\033[0m $1"; }
log_warn()    { echo -e "\033[0;33m[WARN]\033[0m $1"; }
log_step()    { echo -e "\n\033[0;32m==>\033[0m \033[0;34m$1\033[0m"; }

detect_platform() {
    local os cpu
    case "$(uname -s)" in
        Darwin) os="darwin" ;;
        Linux)  os="linux" ;;
        *)      os="unknown" ;;
    esac
    case "$(uname -m)" in
        i386|i486|i586|i686|x86) cpu="386" ;;
        arm64|aarch64) cpu="arm64" ;;
        armv7l|armv7|armv6l|armv6|armhf) cpu="arm" ;;
        x86_64|amd64|AMD64) cpu="amd64" ;;
        *) cpu="unknown" ;;
    esac
    echo "${os}_${cpu}"
}

show_help() {
    cat <<EOF
Build libwebrtc from source at a pinned revision.

Usage: ./scripts/build_libwebrtc_source.sh [OPTIONS]

Options:
  --target PLATFORM      Target platform (darwin_arm64, darwin_amd64, linux_386, linux_amd64, linux_arm64, linux_arm)
  --install-dir DIR      Install prefix for the built archive and headers
  --install-build-deps   Run WebRTC's Linux build dependency installer
  --help                 Show this help

Environment:
  WEBRTC_GIT_REV             Pinned WebRTC revision (default: $WEBRTC_GIT_REV)
  WEBRTC_BRANCH_HEAD         Informational branch-head marker (default: $WEBRTC_BRANCH_HEAD)
  WEBRTC_CACHE_DIR           Checkout/cache location (default: $WEBRTC_CACHE_DIR)
  DEPOT_TOOLS_DIR            depot_tools checkout location (default: $DEPOT_TOOLS_DIR)
  WEBRTC_INSTALL_BUILD_DEPS  Linux-only dependency bootstrap flag (default: $WEBRTC_INSTALL_BUILD_DEPS)
  WEBRTC_GCLIENT_JOBS        gclient parallelism (default: $WEBRTC_GCLIENT_JOBS)

Examples:
  ./scripts/build_libwebrtc_source.sh --target linux_amd64 --install-dir /tmp/libwebrtc
  ./scripts/build_libwebrtc_source.sh --target linux_386 --install-dir /tmp/libwebrtc_x86
  WEBRTC_INSTALL_BUILD_DEPS=1 ./scripts/build_libwebrtc_source.sh --target linux_arm64
EOF
    exit 0
}

target_os_for() {
    case "$1" in
        darwin_*) echo "mac" ;;
        linux_*) echo "linux" ;;
        *) return 1 ;;
    esac
}

out_dir_for() {
    case "$1" in
        darwin_arm64) echo "out/libgowebrtc-darwin-arm64" ;;
        darwin_amd64) echo "out/libgowebrtc-darwin-amd64" ;;
        linux_386)    echo "out/libgowebrtc-linux-x86" ;;
        linux_amd64)  echo "out/libgowebrtc-linux-amd64" ;;
        linux_arm64)  echo "out/libgowebrtc-linux-arm64" ;;
        linux_arm)    echo "out/libgowebrtc-linux-arm" ;;
        *) return 1 ;;
    esac
}

